/**
 * Domain types returned by the {@link POLITELib} client. These are plain
 * TypeScript interfaces, independent of any ORM or database schema.
 */

// ── User & Organization ───────────────────────────────────────────────────────

export interface User {
  id: string;
  name: string;
}

export interface Institution {
  id: string;
  name: string;
}

// ── Semesters & Modules ───────────────────────────────────────────────────────

export interface Semester {
  id: string;
  name: string;
}

export interface Module {
  id: string;
  name: string;
  code: string;
}

// ── Activities ────────────────────────────────────────────────────────────────

interface BaseActivity {
  id: string;
  name: string;
  sortOrder: number;
  parentId: string | null;
}

export interface FolderActivity extends BaseActivity {
  type: "folder";
  description: string;
}

export interface HTMLActivity extends BaseActivity {
  type: "html";
  /** Raw HTML content of the activity page. */
  content: string;
}

export interface WebEmbedActivity extends BaseActivity {
  type: "web_embed";
  /** The URL to embed in an iframe. */
  url: string;
}

export interface DocEmbedActivity extends BaseActivity {
  type: "doc_embed";
  /** Original source file URL (e.g. .pptx, .docx, .pdf). */
  sourceURL: string;
  /** URL of a browser-renderable PDF preview generated by Brightspace, if available. */
  previewURL?: string;
  /** Expiry date of the preview URL, if it is time-limited. */
  previewURLExpiry?: Temporal.Instant;
}

export interface VideoEmbedActivity extends BaseActivity {
  type: "video_embed";
  /** Signed URL of the video file hosted on Brightspace Content Service / S3. */
  sourceURL: string;
  /** Expiry date of the source URL. */
  sourceURLExpiry?: Temporal.Instant;
  /** Signed URL of the video thumbnail. */
  thumbnailURL: string;
  /** Expiry date of the thumbnail URL. */
  thumbnailURLExpiry?: Temporal.Instant;
}

export interface SubmissionActivity extends BaseActivity {
  type: "submission";
  /** ID of the dropbox folder this activity links to. */
  dropboxId: string;
}

export interface QuizActivity extends BaseActivity {
  type: "quiz";
  /** ID of the quiz this activity links to. */
  quizId: string;
}

export interface UnknownActivity extends BaseActivity {
  type: "unknown";
}

export type AnyActivity =
  | FolderActivity
  | HTMLActivity
  | WebEmbedActivity
  | DocEmbedActivity
  | VideoEmbedActivity
  | SubmissionActivity
  | QuizActivity
  | UnknownActivity;

// ── Dropboxes & Submissions ───────────────────────────────────────────────────

export interface SubmissionDropbox {
  id: string;
  name: string;
  moduleId: string;
  description: string;
  dueAt: Temporal.Instant | null;
  opensAt?: Temporal.Instant | null;
  closesAt?: Temporal.Instant | null;
}

export interface Submission {
  id: string;
  dropboxId: string;
  submittedAt: Temporal.Instant | null;
  comment?: string;
}

// ── Quizzes ───────────────────────────────────────────────────────────────────

export interface Quiz {
  id: string;
  moduleId: string;
  name: string;
  description: string;
  dueAt: Temporal.Instant | null;
}
